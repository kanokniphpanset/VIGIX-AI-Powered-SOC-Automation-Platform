const fromPairs = (i: 0 | 1) => Object.fromEntries(Object.entries(PAIRS).map(([k, v]) => [k, v[i]])) as Record<keyof typeof PAIRS, string>
export const th: Record<MsgKey, string> = { ...thCore, ...fromPairs(0) }
export const en: Record<MsgKey, string> = { ...enCore, ...fromPairs(1) }

const DICT: Record<Lang, Record<MsgKey, string>> = { th, en }

export type Params = Record<string, string | number>

/** Text for `key` in `lang` with {placeholders} filled. An unknown key is returned as-is (visible, never blank). */
export function translate(lang: Lang, key: MsgKey, params?: Params): string {
  const text: string = DICT[lang]?.[key] ?? th[key] ?? key
  return params ? text.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m)) : text
}

/** True when `key` is a known message (for keys built from backend enums, e.g. audit actions). */
export const hasMsg = (key: string): key is MsgKey => key in th

export const isLang = (v: unknown): v is Lang => v === 'th' || v === 'en'
